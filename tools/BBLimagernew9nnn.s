	LD	A,'>'
	CALL	TTYOUT
	JR	XWDD1
XWDN:
	CALL	DESDSK
	LD	HL,MSGDON
	LD	DE,DONLEN
	CALL	SENDHL
	JP	BEGIN
;
; XWSAVE - COPY 128-BYTE DATA FIELDS FROM DATA BUFFER TO SHADOW
; SKIPS SA, TA, AND LINK/CRC BYTES (8 BYTES PER SECTOR)
;
XWSAVE:
	LD	HL,DATA+2		; skip SA+TA of first sector
	LD	DE,SHADOW
	LD	B,32
XWSV1:
	LD	C,128
XWSV2:	LD	A,(HL)
	LD	(DE),A
	INC	HL
	INC	DE
	DEC	C
	JR	NZ,XWSV2
	LD	A,L			; skip 8 bytes: BCK(2)+FWD(2)+CRC(2)+SA(1)+TA(1)
	ADD	A,8
	LD	L,A
	JR	NC,XWSV3
	INC	H
XWSV3:	DJNZ	XWSV1
	RET
;
; XWVCMP - COMPARE DATA FIELDS IN DATA BUFFER AGAINST SHADOW
; RETURNS: Z SET IF ALL MATCH, NZ IF ANY MISMATCH
;
XWVCMP:
	LD	HL,SHADOW
	LD	DE,DATA+2		; data field of sector 0
	LD	B,32
XWVC1:
	LD	C,128
XWVC2:	LD	A,(DE)
	CP	(HL)
	RET	NZ			; mismatch - return NZ immediately
	INC	HL
	INC	DE
	DEC	C
	JR	NZ,XWVC2
	LD	A,E			; skip 8 bytes in DATA: BCK+FWD+CRC+SA+TA
	ADD	A,8
	LD	E,A
	JR	NC,XWVC3
	INC	D
XWVC3:	DJNZ	XWVC1
	XOR	A			; all matched - set Z
	RET
;
XWRTRY:	DEFB	0			; retry counter
WRDLY:	DEFB	66			; write gate delay (tunable: try 40-58)
WDLY0:	DEFW	0150H			; index->s0 gap delay counter (tunable)
					; 0x0C00=~2MS, 0x0600=~1MS, 0=none
;
ERRBAD:
	LD	HL,MSGBAD
	LD	DE,BADLEN
	CALL	SENDHL
	JP	BEGIN
;
MSGBAD:	DEFB	0DH,0AH
	DEFM	'BAD SCOPE - USE S/T/D'
	DEFB	0DH,0AH
BADLEN:	EQU	$-MSGBAD
;
NSFERR:
	LD	HL,MSGNSF
	LD	DE,NSFLEN
	CALL	SENDHL
	CALL	DESDSK
	JP	BEGIN
;
; =====================================================
; 'V' COMMAND - BULK ERASE TRACK OR DISK
; SYNTAX: V T TT   (erase one track)
;         V D      (erase whole disk)
; ASSERTS WRITE GATE AND CLOCKS ZEROS CONTINUOUSLY
; FOR ~500MS PER TRACK - NO SECTOR ALIGNMENT.
; DESTROYS ALL SECTOR HEADERS. USE BEFORE F.
; DOES NOT USE CTC/INTERRUPTS - PURE TIMED LOOP.
; =====================================================
;
VERASE:
	CALL	RDSCOPE
	JP	NZ,ERRBAD
	LD	A,(CMDSCOPE)
	CP	'D'
	JP	Z,VERDSK
; TRACK SCOPE
	CALL	SELDSK
	LD	HL,MSGVERT
	LD	DE,VERTLEN
	CALL	SENDHL
	CALL	SEEKTO
	CALL	VERTRK
	LD	A,'T'
	CALL	TTYOUT
	LD	A,(CURTRK)
	CALL	PRHEX2
	LD	A,' '
	CALL	TTYOUT
	LD	HL,MSGDON
	LD	DE,DONLEN
	CALL	SENDHL
	CALL	DESDSK
	JP	BEGIN
;
VERDSK:
	CALL	SELDSK
	CALL	STRK0
	LD	HL,MSGVERD
	LD	DE,VERDLEN
	CALL	SENDHL
VERDL:
	CALL	VERTRK
	LD	A,'T'
	CALL	TTYOUT
	LD	A,(CURTRK)
	CALL	PRHEX2
	LD	A,' '
	CALL	TTYOUT
	LD	A,(CURTRK)
	CP	76
	JR	Z,VERDN
	CALL	HDSTP1
	JR	VERDL
VERDN:
	CALL	DESDSK
	LD	HL,MSGDON
	LD	DE,DONLEN
	CALL	SENDHL
	JP	BEGIN
;
; VERTRK - BULK ERASE ONE TRACK
; DISARMS CTC INTERRUPT DISPATCH, ASSERTS WRITE GATE,
; CLOCKS ZEROS FOR ~500MS (3 x 65536 ITERATIONS),
; THEN DEASSERTS AND RE-ARMS NOTHING (CLEAN STATE FOR F)
;
VERTRK:
	DI
; DISARM INTERRUPT DISPATCH - PREVENT STRAY INTERRUPTS
	LD	A,RSTCLK
	OUT	(CLK0),A
	LD	HL,0
	LD	(DSKVSL),HL
; WRITE GATE ON
	LD	A,WRDAT
	OUT	(DSKCOM),A
; CLOCK ZEROS: 3 OUTER x 65536 INNER = ~500MS AT 4MHZ
	LD	B,3
	CALL	VRTKERASE	; shared erase loop
; WRITE GATE OFF, RESET CTC, RE-ENABLE INTERRUPTS (standalone use)
	XOR	A
	OUT	(DSKCOM),A
	LD	A,RSTCLK
	OUT	(CLK0),A
	EI
	RET
;
; VERTRK2 - BULK ERASE ~3 REVOLUTIONS (~500MS)
; USED INTERNALLY BY XD BEFORE EACH TRACK WRITE
; DOES NOT RE-ENABLE INTERRUPTS - CALLER MANAGES THAT
;
VERTRK2:
	DI
	LD	A,RSTCLK
	OUT	(CLK0),A
	LD	HL,0
	LD	(DSKVSL),HL
	LD	A,WRDAT
	OUT	(DSKCOM),A
	LD	B,3			; 3 REVOLUTIONS FOR BETTER ERASE MARGIN
	CALL	VRTKERASE	; shared erase loop
; WRITE GATE OFF, RESET CTC - NO EI (caller manages interrupts)
	XOR	A
	OUT	(DSKCOM),A
	LD	A,RSTCLK
	OUT	(CLK0),A
	RET
;
; VRTKERASE - SHARED INNER LOOP
; B = outer loop count on entry
;
VRTKERASE:
VRTK1:
	LD	DE,0
VRTK2:
	XOR	A
	OUT	(DSKDAT),A	; CLOCK ZERO BIT
	DEC	DE
	LD	A,D
	OR	E
	JR	NZ,VRTK2
	DJNZ	VRTK1
	RET			; return to caller (VERTRK or VERTRK2)
;
MSGVERT:DEFB	0DH,0AH
	DEFM	'BULK ERASE TRACK: '
VERTLEN:EQU	$-MSGVERT
MSGVERD:DEFB	0DH,0AH
	DEFM	'BULK ERASE DISK'
	DEFB	0DH,0AH
VERDLEN:EQU	$-MSGVERD
;
RXBUF:	EQU	DATA+1100H
XWCNT:	DEFB	0		; SECTOR RECEIVE COUNTER FOR XT DIAGNOSTIC
RXTMO:	DEFB	0		; RXSC0 OUTER TIMEOUT COUNTER
;
SAVSTK:	DEFW	0
STACKE:	EQU	$
STACK:	EQU	$+80H
DATA:	EQU	$+80H
SHADOW:	EQU	DATA+32*136	; 4352 bytes after DATA (RXBUF label is unused)
	END
