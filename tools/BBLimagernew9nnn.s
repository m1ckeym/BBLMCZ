;
; WAIDX - SYNC TO SECTOR 0 BY DETECTING THE INDEX TRIPLET.
; NORMAL GAP ~5MS: B=2. INDEX HALF-GAP ~1.9-2.6MS: B=1 OR B=0.
; GLITCH PULSES (<1MS, B=0, BC<~138) CAN APPEAR BETWEEN THE TWO SHORT GAPS.
; STRATEGY:
;   1. FIND A SHORT GAP (B<2).
;   2. CONSUME SUBSEQUENT GAPS, SKIPPING GLITCHES (BC<0x88=~1MS).
;   3. IF NEXT NON-GLITCH GAP IS ALSO SHORT -> TRIPLET CONFIRMED, RETURN.
;   4. IF NEXT NON-GLITCH GAP IS NORMAL -> FALSE START, RESCAN FROM 1.
; ON RETURN: BOTH SHORT GAPS CONSUMED, WRTRK3 WASEC FIRES ON SECTOR 0.
;
; BC THRESHOLDS (WAIDX2 LOOP = ~7.25US/ITER, RE-ARM ~32US OVERHEAD):
;   GLITCH  <1MS:   BC < 0x88  (132)
;   SHORT   ~2MS:   BC ~ 0x0F0-0x180  -> B=0 OR B=1
;   NORMAL  ~5MS:   BC ~ 0x2B0        -> B=2
;   THRESHOLD FOR SHORT/NORMAL: CP 02H ON B
;   THRESHOLD FOR GLITCH/REAL:  CP 88H ON C WHEN B=0
; WAIDX - SYNC TO SECTOR 0.
; DISK STRUCTURE: ...s31 [~2.5ms] INDEX [~2.5ms] s0 [~5ms] s1...
; DETECT THE FIRST SHORT GAP (s31->INDEX). CTC FIRES ON INDEX HOLE RISING EDGE.
; EXIT IMMEDIATELY - NEXT HOLE IS s0. WRTRK3 WASEC FIRES ON s0.
; DI/EI/NOP/DI DURING COUNT PREVENTS SERIAL RX FROM INFLATING GAP MEASUREMENT.
; NORMAL 5MS GAP: B=2. SHORT 2.5MS GAP: B=1 (OR B=0 FOR VERY SHORT).
; GLITCH FILTER: B=0 AND C<0x88 = PULSE <1MS = IGNORE.
