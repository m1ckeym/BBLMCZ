	LD	HL,SCVEC
	LD	(DSKVSL),HL
	LD	HL,RDTRK2
	LD	(INTPNT),HL
	LD	A,CTRMOD
	OUT	(CLK0),A
	LD	A,1
	OUT	(CLK0),A
	XOR	A
	LD	(SECFLG),A
	LD	(SCCC),A
	LD	BC,0
	DI			; BLOCK SERIAL RX DURING COUNT
WAIDX2:
	INC	BC
	EI			; ALLOW PENDING CTC IRQ TO FIRE AND SET SECFLG
	NOP			; ONE INSTRUCTION BEFORE ANY INTERRUPT
	DI			; BLOCK AGAIN
	LD	A,(DE)
	OR	A
	JR	Z,WAIDX2
	EI			; RE-ENABLE
; CLASSIFY GAP
; WITH DI/EI/NOP/DI LOOP (41T/ITER = 10.25US):
;   NORMAL 5MS GAP: (5000-32)/10.25 = 484 ITERS -> B=1, C=0xE4
;   SHORT 2.5MS GAP: (2500-32)/10.25 = 240 ITERS -> B=0, C=0xF0
;   GLITCH <1MS: B=0, C<0x88
; THRESHOLD CP 01H: B>=1=NORMAL(LOOP), B=0=SHORT OR GLITCH
	LD	A,B
	CP	01H
	JR	NC,WAIDX1	; B>=1 = NORMAL 5MS GAP, KEEP SCANNING
; B=0: SHORT GAP OR GLITCH. CHECK GLITCH FILTER.
	LD	A,C
	CP	088H
	JR	C,WAIDX1	; B=0, C<0x88 -> GLITCH <1MS, IGNORE
; B=0, C>=0x88 -> SHORT GAP = INDEX HOLE. EXIT.
WAIDX_DONE:
; FIRST SHORT GAP CONSUMED = CTC FIRED ON INDEX HOLE RISING EDGE.
; NEXT HOLE IS SECTOR 0. DI SO NO STALE IRQ FIRES BEFORE WRTRK3 WASEC ARMS.
	DI
	LD	HL,0
	LD	(DSKVSL),HL
	RET
